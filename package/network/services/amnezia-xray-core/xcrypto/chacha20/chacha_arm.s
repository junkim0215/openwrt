// ChaCha20 for 32-bit ARM without NEON, one 64-byte block at a time, with
// the 20 rounds unrolled.
//
// Rows a and b of the state (x0-x7) live in R0-R7. Rows c and d (x8-x15)
// live on the stack and are loaded two quarter rounds at a time into R8,
// R9, R12 and R14; the two quarter rounds are interleaved for dual issue.
// R10 (g) and R11 (assembler temporary) are not touched.
//
// The rotations are folded into the barrel shifter: a word of row b or d
// is kept as r with true value ROR(r, p), and every use shifts the operand
// instead of rotating the word. Rows a and c only take additions and stay
// unrotated. After round k every b word carries p = 13k mod 32 and every d
// word p = 8k mod 32, so each round uses fixed shifts; after round 20, b
// carries 4 and d carries 0.
//
// The rounds are written out from the quarter round
//	a += b; d ^= a; d <<<= 16; c += d; b ^= c; b <<<= 12;
//	a += b; d ^= a; d <<<= 8;  c += d; b ^= c; b <<<= 7
// with those pending rotations applied.
//
// Frame layout (offsets from R13):
//	4-67	initial state s0-s15 (s12 is the block counter)
//	68-99	working words x8-x15
//	100	dst pointer, 104 src pointer, 108 blocks left

#define ST(n) (4+4*(n))(R13)
#define X(n) (68+4*((n)-8))(R13)

// Output word n: (x + s) ^ src, stored to dst. x is in reg, src in R9,
// dst in R12; uses R8.
#define OUT(n, reg) \
	MOVW	ST(n), R8;		\
	ADD	R8, reg;		\
	MOVW	(4*(n))(R9), R8;	\
	EOR	R8, reg;		\
	MOVW	reg, (4*(n))(R12)

